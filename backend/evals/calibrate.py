"""Data-driven auto-select thresholds per entity type.

    python -m evals.calibrate --limit 3000            # writes app/detection/thresholds.json
    python -m evals.calibrate --limit 3000 --dry-run  # report only

The engine pre-ticks an entity for redaction when its confidence clears a
threshold. A single hand-picked 0.6 for every type ignores that confidence
means different things per recognizer (a checksum-validated Aadhaar at 1.0 vs
a spaCy ORG guess at 0.34). This sweeps one threshold per entity type on the
DEV splits to maximise token-level F2 (recall-weighted, as leaks cost more
than extra bars), by coordinate ascent: each type in turn, others held fixed,
two passes.

Guards against overfitting noisy labels:
  * dev splits only - test splits and the gold set never inform the fit;
  * thresholds clamped to [MIN_T, MAX_T] so sparse public annotations
    (unlabelled true PII scores as a false positive) can't push a type to an
    extreme;
  * a type needs >= MIN_SUPPORT predictions on dev to move off the default.
Validate the output with `python -m evals.run_detection` on test splits before
keeping it.
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

from evals import datasets as ds
from evals.metrics import prf, score_document
from evals.taxonomy import engine_class

OUT = Path(__file__).resolve().parent.parent / "app" / "detection" / "thresholds.json"
GRID = [round(0.45 + 0.05 * i, 2) for i in range(9)]  # 0.45 .. 0.85
MIN_T, MAX_T = GRID[0], GRID[-1]
MIN_SUPPORT = 30


def collect(engine, samples):
    """Run detection once; keep every candidate with its raw confidence so
    any threshold assignment can be re-scored without re-running the model."""
    cached = []
    for s in samples:
        cached.append((s, engine.detect(s.text)))
    return cached


def score(cached, thresholds, default):
    tp = fp = fn = 0
    for s, entities in cached:
        pred = [
            (e["start"], e["end"], engine_class(e["type"]))
            for e in entities
            if e["confidence"] >= thresholds.get(e["type"], default)
        ]
        c = score_document(s.text, s.spans, pred).counts
        tp, fp, fn = tp + c["tok_tp"], fp + c["tok_fp"], fn + c["tok_fn"]
    return prf(tp, fp, fn)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=3000)
    ap.add_argument("--model", default=None)
    ap.add_argument("--pii-model", default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    from app.detection.engine import AUTO_SELECT_MIN_SCORE, PiiDetectionEngine
    from evals.run_detection import DEFAULT_MODEL

    engine = PiiDetectionEngine(spacy_model=args.model or DEFAULT_MODEL, pii_model_dir=args.pii_model)
    engine.auto_select_thresholds = {}  # calibrate from the uncalibrated default
    samples = ds.load("ai4privacy", "dev", args.limit) + ds.load("gretel", "dev", args.limit)
    cached = collect(engine, samples)

    support = defaultdict(int)
    for _s, ents in cached:
        for e in ents:
            support[e["type"]] += 1
    types = sorted(t for t, n in support.items() if n >= MIN_SUPPORT)

    default = AUTO_SELECT_MIN_SCORE
    thresholds = {}
    base = score(cached, thresholds, default)
    print(f"default {default}: tokR={base['recall']:.3f} tokP={base['precision']:.3f} F2={base['f2']:.3f}")
    for _pass in range(2):
        for t in types:
            best_t, best = thresholds.get(t, default), None
            for cand in GRID:
                m = score(cached, {**thresholds, t: cand}, default)
                if best is None or m["f2"] > best["f2"] + 1e-6:
                    best_t, best = cand, m
            thresholds[t] = best_t
    final = score(cached, thresholds, default)
    print(f"calibrated: tokR={final['recall']:.3f} tokP={final['precision']:.3f} F2={final['f2']:.3f}")
    changed = {t: v for t, v in sorted(thresholds.items()) if abs(v - default) > 1e-9}
    print("changed thresholds:", json.dumps(changed, indent=1))

    if not args.dry_run:
        OUT.write_text(
            json.dumps(
                {
                    "_comment": "Generated by evals/calibrate.py on dev splits (token F2). Delete to revert to the global default.",
                    "default": default,
                    "per_type": changed,
                    "dev_f2_before": round(base["f2"], 4),
                    "dev_f2_after": round(final["f2"], 4),
                },
                indent=2,
            )
        )
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
